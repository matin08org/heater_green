#ifndef HMI_PAGES_H
#define HMI_PAGES_H
#include "HmiImage.h"
#include "HmiText.h"
typedef enum {HMI_BIND_NONE,HMI_BIND_TC1,HMI_BIND_TC2,HMI_BIND_CO,HMI_BIND_CO2,
 HMI_BIND_STATE,HMI_BIND_MODE,HMI_BIND_TARGET,HMI_BIND_SOURCE,HMI_BIND_FAULT,
 HMI_BIND_DAMPER,HMI_BIND_AIR,HMI_BIND_SAMPLE,
 HMI_BIND_MODE_MANUAL,HMI_BIND_MODE_AUTO,HMI_BIND_RUN_STATE,HMI_BIND_STOP_STATE,
 HMI_BIND_GREENHOUSE,HMI_BIND_EXHAUST,HMI_BIND_CO_STATUS,HMI_BIND_CO_VALUE,
 HMI_BIND_CO2_VALUE,HMI_BIND_TARGET_VALUE,HMI_BIND_CO2_STATUS,HMI_BIND_FAULT_STATUS,HMI_BIND_COUNT} HmiBinding;
typedef enum {HMI_PAGE_IMAGE2,HMI_PAGE_RGB565,HMI_PAGE_TEXT,HMI_PAGE_BADGE,HMI_PAGE_IMAGE2_AA} HmiWidgetKind;
typedef struct {
    const char *id;
    HmiWidgetKind kind;
    HmiRect bounds;
    const void *resource; /* HmiImage2*, HmiRgbImage*, or const char* */
    uint16_t colors[4],selected_colors[4];
    HmiBinding binding;
    const char *target_page; /* NULL: display only; route navigation only */
    uint16_t foreground,background;
    HmiTextAlign align;
    bool opaque;
    const HmiFont *font; /* optional per-widget size; NULL uses page font */
    uint8_t radius;
} HmiWidget;
typedef struct {const uint8_t *data;size_t size;uint16_t width,height,stride;} HmiRgbImage;
typedef struct {const char *id;uint16_t background,count;const HmiWidget *widgets;} HmiPage;
typedef struct {
    const HmiPage *page;const HmiFont *font;
    int16_t focus;
    char values[HMI_BIND_COUNT][48];
    uint32_t style_mask;
    uint16_t foreground[HMI_BIND_COUNT],background[HMI_BIND_COUNT];
    uint32_t palette_mask[4];
    uint16_t palettes[128][4]; /* snapshot-owned; never modified while DMA renders it */
} HmiPageView;
/* Generated by Tools/Hmi/Build-Pages.ps1; descriptors and resources read-only. */
extern const HmiPage hmi_pages[];
extern const uint16_t hmi_page_count;
const HmiPage *HmiPages_Find(const HmiPage *pages,uint16_t count,const char *id);
HmiResult HmiPages_Compose(void *snapshot,HmiRect tile,HmiSurface *surface);
/* Draw a single layer, preserving the surface beneath it. Resource/font may be
 * replaced by a DMA-staged RAM descriptor without changing the page snapshot. */
HmiResult HmiPages_DrawWidget(const HmiPageView *view,unsigned index,const HmiWidget *widget,
                            HmiRect tile,HmiSurface *surface);
bool HmiPages_BindingChanged(const HmiPageView *before,const HmiPageView *after,HmiBinding binding);
/* Palette order: background, border, title, graphic. Call before submitting a snapshot. */
bool HmiPages_SetPalette(HmiPageView *view,const char *widget_id,const uint16_t colors[4]);
bool HmiPages_WidgetChanged(const HmiPageView *before,const HmiPageView *after,unsigned index);
#endif
